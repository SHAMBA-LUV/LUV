// gen-poseidon.mjs — emit foundry/src/generated/PoseidonT{N+1}.sol: circomlibjs's Poseidon(N)
// contract as creation bytecode plus a deployer, so Solidity hashes EXACTLY like circuits do.
// (Same parameters as circomlib's Poseidon(N) template and circomlibjs's buildPoseidon.)
//
// Usage: node gen-poseidon.mjs 2 > ../foundry/src/generated/PoseidonT3.sol   (2 inputs: Merkle nodes, nullifiers)
//        node gen-poseidon.mjs 1 > ../foundry/src/generated/PoseidonT2.sol   (1 input: commitments)
// "T" is Poseidon's state width = inputs + 1, the naming used across the ecosystem.
// Generator source: src/poseidon_gencontract.js in https://github.com/iden3/circomlibjs

import { poseidonContract } from 'circomlibjs';

const n = Number(process.argv[2] ?? 2);
if (![1, 2].includes(n)) throw new Error('arity must be 1 or 2');
const t = n + 1;
const code = poseidonContract.createCode(n).replace(/^0x/, '');
const use = n === 2 ? 'Merkle nodes and nullifiers' : 'identity / note commitments';
process.stdout.write(`// SPDX-License-Identifier: GPL-3.0
// AUTO-GENERATED by docs/zk/circom/gen-poseidon.mjs from circomlibjs poseidonContract.createCode(${n}).
// Regenerate: cd docs/zk && npm run build      (bytecode is GPL-3.0, like circomlibjs)
pragma solidity ^0.8.24;

/// Poseidon hash of ${n} field element${n > 1 ? 's' : ''} (${use}) — identical to circomlib's Poseidon(${n}).
interface IPoseidonT${t} {
    function poseidon(uint256[${n}] calldata inputs) external pure returns (uint256);
}

library PoseidonT${t}Deployer {
    error DeployFailed();

    /// Deploys a fresh hasher. On a live network, deploy once and share the address.
    function deploy() internal returns (IPoseidonT${t} hasher) {
        bytes memory code = hex"${code}";
        assembly ("memory-safe") {
            hasher := create(0, add(code, 0x20), mload(code))
        }
        if (address(hasher) == address(0)) revert DeployFailed();
    }
}
`);
