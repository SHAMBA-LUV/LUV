// gen-fixture-calldata.mjs — turn `snarkjs zkey export soliditycalldata` output for a PLONK or
// FFLONK proof ("[24 proof words],[public signals]") into a Solidity fixture library.
//
// Usage: node gen-fixture-calldata.mjs <LibraryName> <uint256|bytes32> calldata.txt > Fixture.sol
//   PLONK verifiers take uint256[24] proofs, FFLONK verifiers take bytes32[24].

import { readFileSync } from 'node:fs';

const [name, kind, path] = process.argv.slice(2);
if (!name || !['uint256', 'bytes32'].includes(kind) || !path) {
  console.error('usage: node gen-fixture-calldata.mjs <LibraryName> <uint256|bytes32> calldata.txt');
  process.exit(2);
}
const words = readFileSync(path, 'utf8').match(/0x[0-9a-fA-F]+/g) ?? [];
if (words.length < 25) throw new Error(`expected ≥ 25 words, got ${words.length}`);
const proof = words.slice(0, 24);
const pub = words.slice(24);
const pad = (w) => '0x' + w.slice(2).padStart(64, '0');
const el = kind === 'bytes32' ? (w) => `bytes32(${pad(w)})` : (w) => `uint256(${pad(w)})`;

process.stdout.write(`// SPDX-License-Identifier: MIT
// AUTO-GENERATED by docs/zk/circom/gen-fixture-calldata.mjs — do not edit. Regenerate: cd docs/zk && npm run build
pragma solidity ^0.8.24;

library ${name} {
    function get() internal pure returns (${kind}[24] memory proof, uint256[${pub.length}] memory pub) {
${proof.map((w, i) => `        proof[${i}] = ${el(w)};`).join('\n')}
${pub.map((w, i) => `        pub[${i}] = ${BigInt(w)};`).join('\n')}
    }
}
`);
