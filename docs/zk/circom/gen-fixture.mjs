// gen-fixture.mjs — turn a snarkjs proof.json + public.json into a Solidity library, so the
// Foundry tests carry real Groth16 proofs with zero cheatcodes and zero file I/O.
//
// Usage: node gen-fixture.mjs <LibraryName> proof.json public.json > Fixture.sol
//
// ⚠ G2 coordinate order: snarkjs stores pi_b as [[x.c0, x.c1], [y.c0, y.c1]], while the
//   EIP-197 pairing precompile expects [[x.c1, x.c0], [y.c1, y.c0]] — each pair is swapped,
//   exactly as `snarkjs zkey export soliditycalldata` does.

import { readFileSync } from 'node:fs';

const [name, proofPath, publicPath] = process.argv.slice(2);
if (!name || !proofPath || !publicPath) {
  console.error('usage: node gen-fixture.mjs <LibraryName> proof.json public.json');
  process.exit(2);
}
const p = JSON.parse(readFileSync(proofPath, 'utf8'));
const pub = JSON.parse(readFileSync(publicPath, 'utf8'));
const n = pub.length;

process.stdout.write(`// SPDX-License-Identifier: MIT
// AUTO-GENERATED by docs/zk/circom/gen-fixture.mjs — do not edit. Regenerate: cd docs/zk && npm run build
pragma solidity ^0.8.24;

library ${name} {
    function get()
        internal
        pure
        returns (uint256[2] memory a, uint256[2][2] memory b, uint256[2] memory c, uint256[${n}] memory pub)
    {
        a = [uint256(${p.pi_a[0]}), uint256(${p.pi_a[1]})];
        b = [
            [uint256(${p.pi_b[0][1]}), uint256(${p.pi_b[0][0]})],
            [uint256(${p.pi_b[1][1]}), uint256(${p.pi_b[1][0]})]
        ];
        c = [uint256(${p.pi_c[0]}), uint256(${p.pi_c[1]})];
${pub.map((v, i) => `        pub[${i}] = ${v};`).join('\n')}
    }
}
`);
